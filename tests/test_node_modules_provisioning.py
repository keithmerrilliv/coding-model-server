def test_validator_rejects_vitest_that_collected_nothing():
    """`Test Files  no tests` is vitest finding zero suites. It exits 0, so
    without this the orchestrator would bank a PASS on an empty run."""
    ok, reason = od._validate_test_output_structure(
        "\n Test Files  no tests\n      Tests  no tests\n", "vitest")
    assert not ok
    assert "vitest summary" in reason


def test_validator_rejects_vitest_module_resolution_failure():
    ok, _ = od._validate_test_output_structure(
        "Error: Cannot find module 'vitest'\n", "vitest")
    assert not ok


def test_validator_rejects_empty_vitest_output():
    ok, _ = od._validate_test_output_structure("   ", "vitest")
    assert not ok


def test_actionable_output_keeps_failures_over_preamble():
    """Truncation must not drop the failures. jest/vitest print a long
    transform/config preamble; a tail-only cut can leave the implementer with
    nothing actionable (the trap the pytest branch already guards against)."""
    preamble = "transform noise\n" * 2000
    body = "\nFAIL Counter.test.jsx > increments\nAssertionError: expected 0 to be 1\n"
    extracted = od._extract_actionable_test_output(preamble + body, "vitest",
                                                   max_chars=2000)
    assert "AssertionError: expected 0 to be 1" in extracted
    assert "transform noise" not in extracted


# ── 5. the acceptance criterion, executed ────────────────────────────────────

_REACT_PKG = {
    "name": "counter-spec", "version": "1.0.0", "private": True, "type": "module",
    "devDependencies": {
        "vitest": "^2.1.8",
        "jsdom": "^25.0.1",
        "react": "^18.3.1",
        "react-dom": "^18.3.1",
        "@testing-library/react": "^16.1.0",
        "@vitejs/plugin-react": "^4.3.4",
    },
}


@requires_install
def test_react_spec_installs_and_passes_end_to_end(tmp_path):
    """DEV-104's acceptance criterion, run rather than asserted about.

    A component + a pure-logic core: dependencies are fetched through the
    network-gated install phase, JSX is transformed, and the component is
    rendered and interacted with under jsdom — all inside the sandbox.
    Everything else in this file mocks the subprocess; this is the one test
    that proves the pieces actually compose.
    """
    spec = tmp_path / "spec"
    _write(spec, "package.json", json.dumps(_REACT_PKG))
    _write(spec, "vitest.config.js",
           "import { defineConfig } from 'vitest/config'\n"
           "import react from '@vitejs/plugin-react'\n"
           "export default defineConfig({ plugins: [react()], "
           "test: { environment: 'jsdom' } })\n")
    _write(spec, "core.js", "export function nextCount(n, step) { return n + step }\n")
    _write(spec, "Counter.jsx",
           "import React, { useState } from 'react'\n"
           "import { nextCount } from './core.js'\n"
           "export default function Counter() {\n"
           "  const [n, setN] = useState(0)\n"
           "  return (<div><span role=\"status\">{n}</span>"
           "<button onClick={() => setN(nextCount(n, 1))}>inc</button></div>)\n"
           "}\n")
    _write(spec, "core.test.js",
           "import { test, expect } from 'vitest'\n"
           "import { nextCount } from './core.js'\n"
           "test('pure core', () => { expect(nextCount(2, 3)).toBe(5) })\n")
    _write(spec, "Counter.test.jsx",
           "import React from 'react'\n"
           "import { test, expect } from 'vitest'\n"
           "import { render, screen, fireEvent } from '@testing-library/react'\n"
           "import Counter from './Counter.jsx'\n"
           "test('renders and increments', () => {\n"
           "  render(<Counter />)\n"
           "  expect(screen.getByRole('status').textContent).toBe('0')\n"
           "  fireEvent.click(screen.getByText('inc'))\n"
           "  expect(screen.getByRole('status').textContent).toBe('1')\n"
           "})\n")

    passed, output = test_runner.run_tests(spec, framework="vitest")

    assert passed, f"React spec should pass end to end:\n{output}"
    assert (spec / "node_modules" / "react").is_dir(), "deps were not provisioned"
    ok, reason = od._validate_test_output_structure(output, "vitest")
    assert ok, f"structural guard rejected a genuine run: {reason}\n{output}"


@requires_install
def test_vitest_run_is_offline(tmp_path):
    """The install phase opens the network; the TEST phase must not inherit it.

    Proven by a test that tries to connect out and only passes when the
    connection is refused — the same shape as the node_test offline test.
    """
    spec = tmp_path / "spec"
    _write(spec, "package.json", json.dumps(
        {"name": "s", "version": "1.0.0", "private": True, "type": "module",
         "devDependencies": {"vitest": "^2.1.8"}}))
    _write(spec, "net.test.js",
           "import { test, expect } from 'vitest'\n"
           "import net from 'node:net'\n"
           "test('no network during tests', () => new Promise((resolve, reject) => {\n"
           "  const s = net.connect(53, '1.1.1.1')\n"
           "  s.on('connect', () => { s.destroy(); reject(new Error('network reachable')) })\n"
           "  s.on('error', () => resolve())\n"
           "}))\n")

    passed, output = test_runner.run_tests(spec, framework="vitest")

    assert passed, f"the connection should have been refused inside the sandbox:\n{output}"
