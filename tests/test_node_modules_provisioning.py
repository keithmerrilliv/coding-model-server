"""DEV-104: node_modules-based JS tests (React via jest/vitest) in the pipeline.

DEV-103 gave the pipeline a zero-dependency `node:test` path. Real React stacks
need `node_modules`, which the test sandbox cannot provide: it is `--unshare-all`
(no network) and there was no dependency-install phase at all.

The design under test: a SEPARATE, network-gated install phase runs
`npm ci`/`npm install --ignore-scripts` with every other confinement still in
force, and the test run afterwards stays offline exactly as before.

The security-relevant claims, and where each is proved:
  1. npm lifecycle scripts never execute — not even when the spec ships an
     `.npmrc` trying to re-enable them  (test_install_scripts_*).
  2. The install phase opens the network and NOTHING else — `/home` stays
     masked, only spec_dir is writable  (test_install_sandbox_*).
  3. The TEST phase is still offline for every framework, including the new
     ones  (test_test_phase_has_no_network, test_vitest_run_is_offline).
  4. `node_test` never gets an install phase, so DEV-103's zero-dependency
     guarantee is intact  (test_node_test_never_provisions).
"""
import json
import os
import shutil
import socket
import subprocess
from pathlib import Path

import pytest

from coding_model_autonomous import test_runner
from coding_model_server import orchestrator_daemon as od


def _write(spec_dir: Path, name: str, content: str) -> None:
    spec_dir.mkdir(parents=True, exist_ok=True)
    (spec_dir / name).write_text(content)


def _has_npm() -> bool:
    root = test_runner.SANDBOX_NODE_ROOT
    return bool(root and (root / "bin" / "npm").exists()) or shutil.which("npm") is not None


def _registry_reachable() -> bool:
    try:
        with socket.create_connection(("registry.npmjs.org", 443), timeout=4):
            return True
    except OSError:
        return False


_NPM = _has_npm()
_BWRAP = shutil.which("bwrap") is not None
_NET = _registry_reachable()

requires_install = pytest.mark.skipif(
    not (_NPM and _BWRAP and _NET),
    reason="needs npm + bwrap + reachable npm registry",
)


# ── 1. install scripts are disabled, unconditionally ─────────────────────────

_LIFECYCLE_PKG = {
    "name": "probe", "version": "1.0.0", "private": True,
    # Every hook npm would fire on a bare `npm install`. Each writes a
    # sentinel; any sentinel on disk afterwards means arbitrary code from an
    # LLM-authored package.json executed on this host.
    "scripts": {
        "preinstall": "node -e \"require('fs').writeFileSync('PWNED_PRE','x')\"",
        "install": "node -e \"require('fs').writeFileSync('PWNED_INSTALL','x')\"",
        "postinstall": "node -e \"require('fs').writeFileSync('PWNED_POST','x')\"",
        "prepare": "node -e \"require('fs').writeFileSync('PWNED_PREPARE','x')\"",
    },
}


@pytest.mark.skipif(not (_NPM and _BWRAP), reason="needs npm + bwrap")
def test_install_scripts_never_run(tmp_path):
    """A package.json full of lifecycle hooks must not execute any of them.

    Needs no network: npm fires the ROOT project's own hooks even with zero
    dependencies to fetch, so this is a fast, exact test of `--ignore-scripts`.
    """
    spec = tmp_path / "spec"
    _write(spec, "package.json", json.dumps(_LIFECYCLE_PKG))

    ok, output = test_runner._provision_node_modules(spec)

    assert ok, f"install should succeed (there is nothing to fetch):\n{output}"
    leaked = sorted(p.name for p in spec.glob("PWNED*"))
    assert leaked == [], f"npm lifecycle scripts executed: {leaked}"


@pytest.mark.skipif(not (_NPM and _BWRAP), reason="needs npm + bwrap")
def test_install_scripts_stay_disabled_against_hostile_npmrc(tmp_path):
    """The spec cannot buy its scripts back with a project-local `.npmrc`.

    npm reads `./.npmrc` from the working directory, and the implementer writes
    that directory. `ignore-scripts=false` there is the obvious bypass. It does
    not work because a CLI flag outranks project config in npm's precedence
    chain — but that is a property of npm, not of our code, so it is worth
    pinning: an npm change here would silently re-open arbitrary code
    execution, and this test is what would catch it.
    """
    spec = tmp_path / "spec"
    _write(spec, "package.json", json.dumps(_LIFECYCLE_PKG))
    _write(spec, ".npmrc", "ignore-scripts=false\n")

    ok, output = test_runner._provision_node_modules(spec)

    assert ok, output
    leaked = sorted(p.name for p in spec.glob("PWNED*"))
    assert leaked == [], f".npmrc re-enabled lifecycle scripts: {leaked}"


def test_install_command_always_passes_ignore_scripts(tmp_path, monkeypatch):
    """No code path may omit --ignore-scripts. Asserted on the argv itself so
    it holds even where npm/bwrap are unavailable to run it for real."""
    seen: dict = {}

    def fake_confined(raw_cmd, spec_dir, timeout, **kw):
        seen["cmd"] = raw_cmd
        seen["kw"] = kw
        return True, ""

    monkeypatch.setattr(test_runner, "_run_confined", fake_confined)
    spec = tmp_path / "spec"
    _write(spec, "package.json", "{}")

    ok, _ = test_runner._provision_node_modules(spec)

    assert ok
    assert "--ignore-scripts" in seen["cmd"]
    assert seen["kw"]["share_net"] is True


# ── 2. install phase: network, and nothing else ──────────────────────────────

def _bind_targets(args: list[str], flag: str) -> list[tuple[str, str]]:
    out = []
    for i, a in enumerate(args):
        if a == flag:
            out.append((args[i + 1], args[i + 2]))
    return out


def test_install_sandbox_shares_net_but_keeps_every_other_confinement(tmp_path):
    spec = tmp_path / "spec"
    spec.mkdir()

    args = test_runner._wrap_in_sandbox(["npm", "install"], spec, share_net=True)

    assert "--share-net" in args, "install phase must reach the registry"
    # --share-net is only defined as a modifier to --unshare-all; order matters.
    assert "--unshare-all" in args
    assert args.index("--unshare-all") < args.index("--share-net")
    # Everything else still holds: homes masked, only spec_dir writable.
    tmpfs = [args[i + 1] for i, a in enumerate(args) if a == "--tmpfs"]
    assert "/home" in tmpfs and "/root" in tmpfs
    assert (str(spec.resolve()), str(spec.resolve())) in _bind_targets(args, "--bind")


def test_test_phase_has_no_network(tmp_path):
    """The default must stay offline — a test that could reach the network
    could exfiltrate whatever it read."""
    spec = tmp_path / "spec"
    spec.mkdir()

    args = test_runner._wrap_in_sandbox(["node", "--test"], spec)

    assert "--share-net" not in args
    assert "--unshare-all" in args


@pytest.mark.parametrize("framework", ["pytest", "node_test", "jest", "vitest"])
def test_run_local_tests_never_requests_network(tmp_path, monkeypatch, framework):
    """The call site, not just the default.

    test_test_phase_has_no_network above pins `_wrap_in_sandbox`'s default,
    which says nothing about what `_run_local_tests` actually passes. Adding
    share_net=True there leaks the network into every test run and only the
    network-gated integration test below notices — and that one skips on any
    host without a registry. This closes the invariant offline.
    """
    seen = {}
    monkeypatch.setattr(test_runner, "_provision_node_modules", lambda d: (True, ""))
    monkeypatch.setattr(test_runner, "_run_confined",
                        lambda cmd, *a, **k: (seen.update(k), (True, ""))[1])
    spec = tmp_path / "spec"
    _write(spec, "package.json", "{}")

    test_runner._run_local_tests(spec, framework, 60)

    assert seen.get("share_net", False) is False, (
        f"{framework} test run requested the network")


def test_resolv_conf_target_is_bound_for_dns(tmp_path):
    """systemd-resolved hosts symlink /etc/resolv.conf into /run, which the
    sandbox does not bind — the link dangles and every lookup fails EAI_AGAIN,
    which surfaces as npm hanging silently until the install timeout. Binding
    the symlink TARGET at its own path is what makes DNS work; binding over
    /etc/resolv.conf itself cannot work (bwrap refuses to create a mount point
    on a dangling symlink).
    """
    spec = tmp_path / "spec"
    spec.mkdir()
    real = Path("/etc/resolv.conf").resolve()

    args = test_runner._wrap_in_sandbox(["npm", "install"], spec, share_net=True)
    offline = test_runner._wrap_in_sandbox(["node", "--test"], spec)

    if real != Path("/etc/resolv.conf") and real.exists():
        # Source and destination must be the SAME path: the point is to make
        # the symlink /etc already provides resolve, not to place the file
        # somewhere new.
        assert (str(real), str(real)) in _bind_targets(args, "--ro-bind-try")
        # And nothing may target /etc/resolv.conf directly — bwrap aborts with
        # "Can't create file at /etc/resolv.conf" when it is a dangling symlink.
        all_dests = [d for _, d in _bind_targets(args, "--ro-bind-try")]
        all_dests += [d for _, d in _bind_targets(args, "--ro-bind")]
        assert "/etc/resolv.conf" not in all_dests
    # Never added to an offline sandbox — it would be pointless there.
    assert "/etc/resolv.conf" not in " ".join(offline)


# ── 3. framework dispatch ────────────────────────────────────────────────────

def test_node_test_never_provisions(tmp_path, monkeypatch):
    """DEV-103's zero-dependency guarantee: a node_test spec must never enter
    the network-gated install phase, even if it happens to ship a package.json."""
    called = []
    monkeypatch.setattr(test_runner, "_provision_node_modules",
                        lambda d: called.append(d) or (True, ""))
    monkeypatch.setattr(test_runner, "_run_confined",
                        lambda *a, **k: (True, "# pass 1\n# fail 0\n"))
    spec = tmp_path / "spec"
    _write(spec, "package.json", json.dumps({"dependencies": {"react": "^18"}}))
    _write(spec, "a.test.js", "")

    test_runner._run_local_tests(spec, "node_test", 60)

    assert called == [], "node_test must not trigger a dependency install"


@pytest.mark.parametrize("framework", ["jest", "vitest"])
def test_node_modules_frameworks_provision_first(tmp_path, monkeypatch, framework):
    order = []
    monkeypatch.setattr(test_runner, "_provision_node_modules",
                        lambda d: order.append("install") or (True, ""))
    monkeypatch.setattr(test_runner, "_run_confined",
                        lambda *a, **k: order.append("test") or (True, ""))
    spec = tmp_path / "spec"
    _write(spec, "package.json", "{}")

    test_runner._run_local_tests(spec, framework, 60)

    assert order == ["install", "test"]


def test_failed_install_short_circuits_the_test_run(tmp_path, monkeypatch):
    """A failed install must not fall through into a test run — the tests would
    fail on missing modules and the real cause would be buried."""
    monkeypatch.setattr(test_runner, "_provision_node_modules",
                        lambda d: (False, "ENOTFOUND registry.npmjs.org"))
    ran = []
    monkeypatch.setattr(test_runner, "_run_confined",
                        lambda *a, **k: ran.append(1) or (True, ""))
    spec = tmp_path / "spec"
    _write(spec, "package.json", "{}")

    passed, output = test_runner._run_local_tests(spec, "vitest", 60)

    assert not passed
    assert ran == [], "tests must not run when dependencies are missing"
    assert "ENOTFOUND" in output


def test_provision_is_a_noop_without_package_json(tmp_path, monkeypatch):
    monkeypatch.setattr(test_runner, "_run_confined",
                        lambda *a, **k: pytest.fail("should not shell out"))
    ok, output = test_runner._provision_node_modules(tmp_path)
    assert ok and output == ""


def test_npm_ci_used_only_with_a_lockfile(tmp_path, monkeypatch):
    """`npm ci` is the pinned path, but it hard-fails when the lockfile
    disagrees with package.json — the normal outcome when a model writes both
    by hand. Fresh resolution is the fallback when no lockfile is present."""
    seen = {}
    monkeypatch.setattr(test_runner, "_run_confined",
                        lambda cmd, *a, **k: (seen.update(cmd=cmd), (True, ""))[1])
    spec = tmp_path / "spec"
    _write(spec, "package.json", "{}")

    test_runner._provision_node_modules(spec)
    assert seen["cmd"][:2] == ["npm", "install"]

    _write(spec, "package-lock.json", "{}")
    test_runner._provision_node_modules(spec)
    assert seen["cmd"][:2] == ["npm", "ci"]


def test_vitest_and_jest_use_local_binaries_and_skip_retry_history(tmp_path, monkeypatch):
    """Two regressions in one shape.

    `npx jest` would try to FETCH jest from the registry inside the offline
    test sandbox. And retry_history/ holds snapshots of every prior attempt —
    collecting them re-runs a fixed bug's old failure forever, which is what
    killed spec_54b2c1b3 on the node_test path (DEV-103).
    """
    seen = {}
    monkeypatch.setattr(test_runner, "_provision_node_modules", lambda d: (True, ""))
    monkeypatch.setattr(test_runner, "_run_confined",
                        lambda cmd, *a, **k: (seen.update(cmd=cmd), (True, ""))[1])
    spec = tmp_path / "spec"
    _write(spec, "package.json", "{}")

    test_runner._run_local_tests(spec, "jest", 60)
    assert seen["cmd"][0] == "node_modules/.bin/jest"
    assert "npx" not in seen["cmd"]
    joined = " ".join(seen["cmd"])
    assert "/retry_history/" in joined
    # Overriding the ignore list REPLACES jest's defaults, so node_modules has
    # to be restated or jest collects every installed package's own tests.
    assert "/node_modules/" in joined

    test_runner._run_local_tests(spec, "vitest", 60)
    assert seen["cmd"][0] == "node_modules/.bin/vitest"
    # Without `run`, vitest starts a watch server and never exits.
    assert seen["cmd"][1] == "run"
    joined = " ".join(seen["cmd"])
    assert "**/retry_history/**" in joined and "**/node_modules/**" in joined


